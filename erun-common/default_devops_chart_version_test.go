// TestEnsureDefaultDevopsChartDoesNotTouchSiblingBackendCharts is
// the safety check that the legacy upgrade is scoped by `description:
// ERun DevOps`. The default tenant tree also lays down backend-api /
// backend-db / backend-postgres charts whose Chart.yaml files share
// the base name; rewriting those by mistake would silently flip
// images for unrelated services.
func TestEnsureDefaultDevopsChartDoesNotTouchSiblingBackendCharts(t *testing.T) {
	projectRoot := t.TempDir()
	moduleName := RuntimeReleaseName("tenant-a")
	backendChart := filepath.Join(projectRoot, moduleName, "k8s", "erun-backend-api", "Chart.yaml")
	if err := os.MkdirAll(filepath.Dir(backendChart), 0o755); err != nil {
		t.Fatalf("mkdir backend chart dir: %v", err)
	}
	original := "apiVersion: v2\nname: erun-backend-api\ndescription: ERun backend API\ntype: application\nversion: \"1.0.0\"\nappVersion: \"1.0.0\"\n"
	if err := os.WriteFile(backendChart, []byte(original), 0o644); err != nil {
		t.Fatalf("write backend Chart.yaml: %v", err)
	}

	if err := EnsureDefaultDevopsChartWithVersion(Context{}, projectRoot, "tenant-a", DefaultEnvironment, "1.0.75"); err != nil {
		t.Fatalf("EnsureDefaultDevopsChartWithVersion failed: %v", err)
	}

	got, err := os.ReadFile(backendChart)
	if err != nil {
		t.Fatalf("read backend Chart.yaml: %v", err)
	}
	if string(got) != original {
		t.Fatalf("backend Chart.yaml was rewritten by the devops migration; got:\n%s", got)
	}
}
