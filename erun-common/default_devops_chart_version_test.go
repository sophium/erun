// TestEnsureDefaultDevopsChartUpgradesLegacyAppVersionOnDisk locks
// the migration path for existing tenant charts. A user whose
// `<tenant>-devops/k8s/<tenant>-devops/Chart.yaml` was generated by
// an older binary still carries `appVersion: "1.0.0"` and the helm
// renders point at non-existent images. The next
// EnsureDefaultDevopsChartWithVersion call must rewrite that file
// in place; non-devops Chart.yaml files (backend-* siblings) must
// stay untouched so this migration cannot accidentally clobber a
// modified tenant chart.
func TestEnsureDefaultDevopsChartUpgradesLegacyAppVersionOnDisk(t *testing.T) {
	projectRoot := t.TempDir()
	moduleName := RuntimeReleaseName("tenant-a")
	chartPath := filepath.Join(projectRoot, moduleName, "k8s", moduleName, "Chart.yaml")
	if err := os.MkdirAll(filepath.Dir(chartPath), 0o755); err != nil {
		t.Fatalf("mkdir Chart.yaml dir: %v", err)
	}
	legacy := "apiVersion: v2\nname: " + moduleName + "\ndescription: ERun DevOps\ntype: application\nversion: \"1.0.0\"\nappVersion: \"1.0.0\"\n"
	if err := os.WriteFile(chartPath, []byte(legacy), 0o644); err != nil {
		t.Fatalf("write legacy Chart.yaml: %v", err)
	}

	if err := EnsureDefaultDevopsChartWithVersion(Context{}, projectRoot, "tenant-a", DefaultEnvironment, "1.0.75"); err != nil {
		t.Fatalf("EnsureDefaultDevopsChartWithVersion failed: %v", err)
	}

	got, err := os.ReadFile(chartPath)
	if err != nil {
		t.Fatalf("read upgraded Chart.yaml: %v", err)
	}
	for _, want := range []string{
		`version: "1.0.75"`,
		`appVersion: "1.0.75"`,
	} {
		if !strings.Contains(string(got), want) {
			t.Fatalf("expected %q after upgrade, got:\n%s", want, got)
		}
	}
}

