// TestMigrateDefaultDevopsChartAppVersionRewritesLegacyChart is the
// narrow `erun open` counterpart to the EnsureDefaultDevopsChart
// upgrade test: a tenant whose Chart.yaml was generated by an older
// binary must have appVersion lifted in place the next time the
// rebuilt binary runs `erun open`, without writing any of the
// backend-* chart scaffolding the user did not ask for.
func TestMigrateDefaultDevopsChartAppVersionRewritesLegacyChart(t *testing.T) {
	projectRoot := t.TempDir()
	moduleName := RuntimeReleaseName("tenant-a")
	chartPath := filepath.Join(projectRoot, moduleName, "k8s", moduleName, "Chart.yaml")
	if err := os.MkdirAll(filepath.Dir(chartPath), 0o755); err != nil {
		t.Fatalf("mkdir Chart.yaml dir: %v", err)
	}
	legacy := "apiVersion: v2\nname: " + moduleName + "\ndescription: ERun DevOps\ntype: application\nversion: \"1.0.0\"\nappVersion: \"1.0.0\"\n"
	if err := os.WriteFile(chartPath, []byte(legacy), 0o644); err != nil {
		t.Fatalf("write legacy Chart.yaml: %v", err)
	}

	if err := MigrateDefaultDevopsChartAppVersion(Context{}, projectRoot, "tenant-a", "1.0.75"); err != nil {
		t.Fatalf("MigrateDefaultDevopsChartAppVersion failed: %v", err)
	}

	got, err := os.ReadFile(chartPath)
	if err != nil {
		t.Fatalf("read upgraded Chart.yaml: %v", err)
	}
	for _, want := range []string{
		`version: "1.0.75"`,
		`appVersion: "1.0.75"`,
	} {
		if !strings.Contains(string(got), want) {
			t.Fatalf("expected %q after migration, got:\n%s", want, got)
		}
	}

	// The narrow migration must not create the backend-* charts the
	// full EnsureDefaultDevopsChartWithVersion would. A tenant who
	// did not opt into them keeps a minimal repo.
	for _, sibling := range []string{"erun-backend-api", "erun-backend-db", "erun-backend-postgres"} {
		siblingChart := filepath.Join(projectRoot, moduleName, "k8s", sibling, "Chart.yaml")
		if _, err := os.Stat(siblingChart); !os.IsNotExist(err) {
			t.Fatalf("expected %s to remain absent after narrow migration, stat err=%v", siblingChart, err)
		}
	}
}

