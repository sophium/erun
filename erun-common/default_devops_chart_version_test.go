// TestEnsureDefaultDevopsChartBakesAppVersionIntoChartYAML locks the
// generator side of issue #361: the materialized tenant Chart.yaml
// must carry the resolved appVersion, not the asset's literal
// placeholder. Helm reads `.Chart.AppVersion` for the runtime image
// tags (erun-mcp, <tenant>-devops, …), so a stale placeholder pins
// every tenant to a non-existent or year-old image.
func TestEnsureDefaultDevopsChartBakesAppVersionIntoChartYAML(t *testing.T) {
	projectRoot := t.TempDir()
	if err := EnsureDefaultDevopsChartWithVersion(Context{}, projectRoot, "tenant-a", DefaultEnvironment, "1.0.75"); err != nil {
		t.Fatalf("EnsureDefaultDevopsChartWithVersion failed: %v", err)
	}
	moduleName := RuntimeReleaseName("tenant-a")
	chartPath := filepath.Join(projectRoot, moduleName, "k8s", moduleName, "Chart.yaml")
	data, err := os.ReadFile(chartPath)
	if err != nil {
		t.Fatalf("read generated Chart.yaml: %v", err)
	}
	content := string(data)
	if strings.Contains(content, "__APP_VERSION__") {
		t.Fatalf("placeholder leaked into generated Chart.yaml:\n%s", content)
	}
	for _, want := range []string{
		`version: "1.0.75"`,
		`appVersion: "1.0.75"`,
	} {
		if !strings.Contains(content, want) {
			t.Fatalf("expected %q in generated Chart.yaml:\n%s", want, content)
		}
	}
}

